"""Regenerate recipes/index.md from each recipe.md frontmatter."""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECIPES = os.path.join(ROOT, "recipes")
REQUIRED = ("title", "intent", "data_shape", "functions")

FRONTMATTER = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.S)


def parse_frontmatter(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    match = FRONTMATTER.match(text)
    if not match:
        raise ValueError(f"{path}: missing --- frontmatter block")
    meta = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip().strip('"').strip("'")
    missing = [k for k in REQUIRED if not meta.get(k)]
    if missing:
        raise ValueError(f"{path}: missing keys {missing}")
    return meta


def collect():
    entries = []
    for name in sorted(os.listdir(RECIPES)):
        folder = os.path.join(RECIPES, name)
        recipe_md = os.path.join(folder, "recipe.md")
        if not os.path.isdir(folder) or not os.path.exists(recipe_md):
            continue
        meta = parse_frontmatter(recipe_md)
        meta["slug"] = name
        meta["has_script"] = os.path.exists(os.path.join(folder, "plot.py"))
        entries.append(meta)
    return entries


def render(entries):
    lines = [
        "# Recipe index",
        "",
        "Generated by `scripts/list_recipes.py` from each `recipe.md`; do not edit by hand.",
        "",
        "Read the row that matches the request, then open `recipe.md` and `plot.py`",
        "in that folder. Each folder is self-contained and runnable:",
        "`python recipes/<slug>/plot.py --out DIR` (writes to a temp dir by default).",
        "",
        "| Recipe | Use for | Data shape | Functions |",
        "| --- | --- | --- | --- |",
    ]
    for e in entries:
        link = f"[{e['title']}]({e['slug']}/recipe.md)"
        funcs = ", ".join(f"`{f.strip()}`" for f in e["functions"].split(",") if f.strip())
        lines.append(f"| {link} | {e['intent']} | {e['data_shape']} | {funcs} |")
    lines.append("")
    return "\n".join(lines)


def main():
    entries = collect()
    out = os.path.join(RECIPES, "index.md")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(entries))
    print(f"wrote {out} ({len(entries)} recipes)")
    for e in entries:
        if not e["has_script"]:
            print(f"  {e['slug']}: missing plot.py")


if __name__ == "__main__":
    main()
